#!/usr/bin/env node
'use strict';
/**
 * Install or remove the Cline hook stubs.
 *
 *   node adapters/cline/install.js                      ~/.cline/hooks (all workspaces)
 *   node adapters/cline/install.js --workspace <dir>    <dir>/.clinerules/hooks only
 *   node adapters/cline/install.js --uninstall [--workspace <dir>]
 *
 * Each stub is a one-line TaskStart.js / UserPromptSubmit.js that requires
 * hook.js from this folder. A stub is only overwritten or deleted when it
 * carries MARKER, so hooks you wrote yourself are never touched.
 */
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const MARKER = 'session-namer cline adapter';
const HOOK_FILES = ['TaskStart.js', 'UserPromptSubmit.js'];

function hooksDir({ workspace = null, env = process.env } = {}) {
  if (workspace) return path.join(path.resolve(workspace), '.clinerules', 'hooks');
  const clineDir = env.CLINE_DIR && env.CLINE_DIR.trim() ? env.CLINE_DIR.trim() : path.join(os.homedir(), '.cline');
  return path.join(clineDir, 'hooks');
}

function stubSource(hookPath) {
  return `// ${MARKER} (generated by install.js; safe to delete)\nrequire(${JSON.stringify(hookPath)}).main();\n`;
}

const isOurs = (file) => {
  try { return fs.readFileSync(file, 'utf8').includes(MARKER); } catch { return false; }
};

function install(dir, hookPath = path.join(__dirname, 'hook.js')) {
  fs.mkdirSync(dir, { recursive: true });
  const done = [];
  for (const name of HOOK_FILES) {
    const file = path.join(dir, name);
    if (fs.existsSync(file) && !isOurs(file)) {
      done.push(`skipped ${file} (exists and is not ours)`);
      continue;
    }
    fs.writeFileSync(file, stubSource(hookPath), { mode: 0o755 });
    fs.chmodSync(file, 0o755);
    done.push(`wrote ${file}`);
  }
  return done;
}

function uninstall(dir) {
  const done = [];
  for (const name of HOOK_FILES) {
    const file = path.join(dir, name);
    if (isOurs(file)) {
      fs.unlinkSync(file);
      done.push(`removed ${file}`);
    }
  }
  return done;
}

function main(argv = process.argv.slice(2)) {
  const wsIdx = argv.indexOf('--workspace');
  const workspace = wsIdx >= 0 ? argv[wsIdx + 1] : null;
  const dir = hooksDir({ workspace });
  const lines = argv.includes('--uninstall') ? uninstall(dir) : install(dir);
  for (const l of lines.length ? lines : ['nothing to do']) process.stdout.write(`${l}\n`);
}

if (require.main === module) main();

module.exports = { install, uninstall, hooksDir, stubSource, MARKER, HOOK_FILES };
